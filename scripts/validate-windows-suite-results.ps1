# Validates coverage only. Native attestation remains owned by qualify-runtime-final.ps1.
param(
    [Parameter(Mandatory=$true)][string]$ProjectRoot,
    [Parameter(Mandatory=$true)][string]$ResultsDirectory,
    [Parameter(Mandatory=$true)][string]$ExpectedSuitesPath,
    [Parameter(Mandatory=$true)][string]$DependencyStatus
)
$ErrorActionPreference = 'Stop'
if ($DependencyStatus -cne 'success') { throw "native suite dependency did not succeed: $DependencyStatus" }
$root = (Resolve-Path -LiteralPath $ProjectRoot).Path
# Use discovery from this aggregate's checkout, not the matrix's supplied list alone.
# Assign before wrapping: Windows PS5.1 emits a JSON array as one pipeline object.
$actualParsed = & (Join-Path $root 'tests/template/run-all.ps1') -ListSuites | ConvertFrom-Json
$actual = @($actualParsed)
$expectedParsed = ConvertFrom-Json ([IO.File]::ReadAllText($ExpectedSuitesPath))
$expected = @($expectedParsed)
if ($expected.Count -ne $actual.Count -or @($expected | Select-Object -Unique).Count -ne $expected.Count) { throw 'discovery suite count/duplicates mismatch' }
foreach ($name in $actual) { if ($name -cnotin $expected) { throw "discovery differs from exact checkout: $name" } }
$head = & git -C $root rev-parse HEAD; if ($LASTEXITCODE -ne 0) { throw 'cannot resolve aggregate HEAD' }
$tree = & git -C $root rev-parse 'HEAD^{tree}'; if ($LASTEXITCODE -ne 0) { throw 'cannot resolve aggregate tree' }
$status = @(& git -C $root status --porcelain --untracked-files=all)
if ($LASTEXITCODE -ne 0 -or $status.Count -ne 0) { throw 'aggregate checkout must be clean' }
$files = @(Get-ChildItem -LiteralPath $ResultsDirectory -Recurse -File -Filter '*.result.json')
if ($files.Count -ne $actual.Count) { throw "native coverage incomplete/duplicate: expected $($actual.Count), found $($files.Count)" }
$seen = @()
foreach ($file in $files) {
    $r = ConvertFrom-Json ([IO.File]::ReadAllText($file.FullName))
    if ($r.format -cne 'forge-windows-suite-v1' -or $r.suite -cnotin $actual -or $r.suite -cin $seen) { throw "unknown or duplicate suite result: $($r.suite)" }
    $seen += $r.suite
    if (($r.exit_code -isnot [int] -and $r.exit_code -isnot [long]) -or $r.exit_code -ne 0) { throw "suite failed or missing exit: $($r.suite)" }
    if (($r.ps_major -isnot [int] -and $r.ps_major -isnot [long]) -or ($r.ps_minor -isnot [int] -and $r.ps_minor -isnot [long]) -or $r.ps_major -ne 5 -or $r.ps_minor -ne 1 -or $r.os -cne 'Windows_NT') { throw "suite lacks native Windows PowerShell 5.1: $($r.suite)" }
    foreach ($key in @('head_before','head_after')) { if ($r.$key -cne $head) { throw "suite HEAD mismatch: $($r.suite) $key" } }
    foreach ($key in @('tree_before','tree_after')) { if ($r.$key -cne $tree) { throw "suite tree mismatch: $($r.suite) $key" } }
    foreach ($key in @('clean_before','clean_after')) { if ($r.$key -isnot [bool] -or -not $r.$key) { throw "suite candidate dirty/missing: $($r.suite) $key" } }
    if ($r.elapsed_seconds -isnot [ValueType] -or $r.elapsed_seconds -is [bool] -or $r.elapsed_seconds -lt 0 -or [double]::IsNaN([double]$r.elapsed_seconds) -or [double]::IsInfinity([double]$r.elapsed_seconds)) { throw "invalid elapsed result: $($r.suite)" }
    Write-Host "NATIVE_SUITE_VALID name=$($r.suite) exit=0 elapsed_s=$($r.elapsed_seconds)"
}
Write-Host "PASS: complete exact-candidate native coverage ($($actual.Count) suites); attestation not generated by validator"
